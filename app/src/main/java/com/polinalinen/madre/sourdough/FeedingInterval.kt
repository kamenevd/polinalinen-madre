package com.polinalinen.madre.sourdough

/**
 * Cycle 19: как часто кормить — словами, которыми это говорят на кухне.
 *
 * В базе интервал лежит часами, и не по прихоти: intervalHours — ключ, от
 * которого считается фаза закваски (`profileForInterval`). Но «раз в 72 часа»
 * человек про свою закваску не говорит; он говорит «раз в три дня». Перевод
 * живёт здесь, а не внутри composable, по двум причинам: список ключей обязан
 * совпадать с тем, что понимает профиль, и это проверяется тестом, а не
 * глазами; а строка настройки и строка дневника не имеют права разойтись.
 */
object FeedingInterval {

    /**
     * Что книга предлагает выбрать. Те же пять ключей, что понимает
     * `profileForInterval`: записать в базу число, от которого фаза посчитается
     * неверно, колофон не должен уметь.
     */
    val HOURS = listOf(12, 24, 48, 72, 168)

    /**
     * Двенадцать часов остались часами намеренно: «два раза в сутки» — это
     * другое обещание (утром и вечером), а книга считает ровно от последнего
     * кормления.
     */
    fun label(hours: Int): String = when (hours) {
        12 -> "раз в 12 часов"
        24 -> "раз в сутки"
        48 -> "раз в два дня"
        72 -> "раз в три дня"
        168 -> "раз в неделю"
        // В базе может оказаться значение, которого книга больше не предлагает
        // (например, оставшееся от прошлой версии). Придумывать ему красивое имя
        // нельзя — книга называет его как есть.
        else -> "каждые $hours часов"
    }
}
