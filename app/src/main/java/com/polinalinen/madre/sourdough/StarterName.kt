package com.polinalinen.madre.sourdough

/**
 * Cycle 14: закваску зовут так, как её назвали в семье.
 *
 * До этого цикла имя было написано в коде трижды — в колофоне строкой без
 * кнопки, в дневнике заголовком и в подписи фотокарточки, — а четвёртое,
 * настоящее, лежало в sourdough_configs и не показывалось нигде. Теперь имя
 * одно, живёт в Room и приводится к общему виду здесь: экраны не должны
 * каждый по-своему решать, что делать с пустой строкой или переносом строки,
 * иначе дневник, колофон и напоминание разойдутся в написании одного имени.
 */
object StarterName {

    /** Как книга звала закваску с самого начала — и зовёт, пока не переназвали. */
    const val DEFAULT = "Мадре"

    /**
     * Имя едет в заголовок уведомления и в строку колофона: длиннее одной
     * строки оно там всё равно не покажется, а обрезать по месту показа —
     * значит обрезать в каждом месте по-разному.
     */
    const val MAX_LENGTH = 24

    /**
     * Одна строка без хвостов. Пустое имя — не имя: закваска остаётся Мадре,
     * а не становится безымянной.
     */
    fun sanitize(raw: String): String {
        val oneLine = raw.replace(WHITESPACE, " ").trim()
        if (oneLine.isEmpty()) return DEFAULT
        return oneLine.take(MAX_LENGTH).trim()
    }

    /** Заголовок дневника: «Соня пишет:». */
    fun diaryTitle(name: String): String = "${sanitize(name)} пишет:"

    /** Надстрочная подпись на первой полосе — та же, но без двоеточия. */
    fun homeLabel(name: String): String = "${sanitize(name)} пишет"

    /**
     * Подпись фотокарточки кормления. Точка вместо родительного падежа
     * намеренно: «Кормление Соня» книга не напишет, а склонять чужое имя
     * ей нечем.
     */
    fun feedingPhotoCaption(name: String): String = "Кормление · ${sanitize(name)}"

    /**
     * Заголовок напоминания. Без «проголодалась»: род имени книге неизвестен,
     * и «Борис проголодалась» — не то, что человек должен прочитать в шторке.
     */
    fun hungryTitle(name: String): String = "${sanitize(name)}: пора кормить"

    private val WHITESPACE = Regex("\\s+")
}
