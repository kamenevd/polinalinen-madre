package com.polinalinen.madre.sourdough

/**
 * Cycle 14: переименование, набранное раньше, чем книга успела открыться.
 *
 * Конфиг закваски приезжает из Room асинхронно, и первые доли секунды после
 * входа в колофон писать имя ещё некуда. До этой правки такое имя молча
 * пропадало: поле показывало набранное слово — человек видел «Соня» и уходил, —
 * а в базе оставалась «Мадре». Экран говорил «сохранено» там, где сохранять
 * было нечем.
 *
 * Здесь набранное имя ждёт конфига и уходит в базу первым же делом, как только
 * тот появился. Очередь глубиной ровно в одно имя: важно последнее набранное, а
 * не история нажатий.
 *
 * Класс отдельный и без Android внутри, потому что тонкость здесь одна и её
 * надо проверить тестом: имя, набранное ПОСЛЕ загрузки конфига, не имеет права
 * быть затёртым тем, что стояло в очереди до неё.
 */
class StarterRenameQueue {

    private var pending: String? = null

    /**
     * Человек переименовал закваску. [configId] — конфиг, если он уже загружен.
     *
     * Возвращает id, в который надо писать прямо сейчас, либо null — имя встало
     * в очередь и уйдёт в базу из [flush].
     */
    fun rename(configId: Long?, name: String): Long? {
        if (configId == null) {
            pending = name
            return null
        }
        // Конфиг уже есть — пишем сразу, а очередь чистим: то, что набрано
        // сейчас, новее того, что ждало загрузки, и затирать его нельзя.
        pending = null
        return configId
    }

    /**
     * Конфиг загрузился. Возвращает имя, которое ждало записи, либо null, если
     * ничего не набирали. Второй раз то же имя не вернётся.
     */
    fun flush(): String? {
        val queued = pending
        pending = null
        return queued
    }
}
