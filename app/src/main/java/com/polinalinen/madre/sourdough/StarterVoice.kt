    fun nextIndex(lastShown: Int, count: Int = LINES.size): Int {
        if (count <= 0) return 0
        return (lastShown + 1).mod(count)
    }

    fun lineAt(index: Int): String {
        if (LINES.isEmpty()) return ""
        return LINES[index.mod(LINES.size)]
    }

    fun advance(lastShown: Int): Pair<Int, String> {
        val index = nextIndex(lastShown)
        return index to lineAt(index)
    }
