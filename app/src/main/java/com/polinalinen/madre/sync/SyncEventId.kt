package com.polinalinen.madre.sync

/**
 * Cycle 15: ключ идемпотентности для общей книги — «<устройство>-<событие>».
 *
 * Что он закрывает: одно и то же событие, доставленное дважды. Очередь
 * WorkManager переживает и потерю сети, и перезагрузку, и обновление
 * приложения; кнопка «Поделиться» на Complete-экране жмётся второй раз; POST
 * успевает дойти до сервера, а ответ — потеряться, и запрос уходит на повтор.
 * Во всех этих случаях запись у сервера одна, потому что ключ тот же.
 *
 * Чего он НЕ закрывает, и это важно понимать честно: два человека, накормившие
 * закваску одновременно со своих телефонов, — это два разных события на двух
 * разных устройствах. Ключи у них разные по построению, и записей на сервере
 * будет две. Свести их в одну может только смысловой ключ (семья + время с
 * точностью до окна), а не этот — и такое решение стоит принимать отдельно,
 * потому что оно способно склеить два настоящих кормления.
 *
 * Чистые функции без Context: сам device_id берётся из [DeviceIdentity].
 */
object SyncEventId {

    /**
     * Ключ выпечки — id её строки в bake_records.
     *
     * Cycle 17 исправляет здесь ошибку, из-за которой ключ не работал вовсе.
     * Раньше сюда шёл номер СЕССИИ, и KDoc уверял, что он «уникален на
     * устройстве и не переиспользуется». Это неправда: счёт сессий заводится
     * заново в каждом процессе приложения и продолжается только с той строки
     * active_bakes, что ждёт восстановления. Как только все выпечки завершены,
     * таблица пуста — и следующая выпечка после перезапуска снова получает
     * номер 1. Ключ у неё выходил тот же, что у самой первой выпечки в жизни
     * телефона, и сервер, честно дедуплицируя по ключу, выбрасывал её.
     *
     * id из bake_records — автоинкремент SQLite: он не начинается заново и не
     * переиспользуется, пока жива сама книга. То есть ровно то свойство,
     * которое здесь и требовалось.
     */
    fun forBake(deviceId: String, recordId: Long): String = "$deviceId-$recordId"

    /** Ключ кормления: id строки feedings — он тоже на устройстве уникален. */
    fun forFeeding(deviceId: String, feedingId: Long): String = "$deviceId-$feedingId"
}
