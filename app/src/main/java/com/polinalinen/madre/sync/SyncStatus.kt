package com.polinalinen.madre.sync

import android.content.SharedPreferences

/**
 * Cycle 17: чем кончилась последняя отправка в общую книгу.
 *
 * Отправка идёт из WorkManager, то есть уже после того, как человек ушёл с
 * экрана «Испечено». Сказать ему о неудаче в тот момент нечем и незачем: тоста
 * он не увидит, а если увидит — это будет тост посреди чужого приложения. Но
 * молчать тоже нельзя: до Cycle 17 ни одна отправка не доходила (коллекции
 * стояли закрытыми), и книга не подавала об этом ни звука.
 *
 * Поэтому исход последней попытки просто лежит здесь, а «Выходные данные»
 * показывают его строкой — там, где человек и так читает про то, что в книге
 * работает, а что нет.
 *
 * [line] — чистая функция: текст проверяется юнит-тестом без Android.
 */
object SyncStatus {

    /**
     * Различаем не коды ответа, а то, что человеку делать. «Войдите» и
     * «подождите сети» — разные советы, и склеивать их в одно «не получилось»
     * значит не сказать ничего.
     */
    enum class State {
        /** Отправок ещё не было — книге нечего сообщать. */
        IDLE,

        /** Последняя запись доставлена. */
        DELIVERED,

        /** Аккаунта нет: общая книга просто не подключена, и это законно. */
        NO_ACCOUNT,

        /** Сервер не принял вход — 401/403. Токен протух или семьи больше нет. */
        DENIED,

        /** Сети нет или сервер молчит: доставка отложена, не потеряна. */
        UNREACHABLE,

        /** Сервер отказался принимать запись и повтор не поможет. */
        REJECTED,
    }

    const val PREFS = "madre_prefs"
    const val KEY = "sync_last_state"

    fun record(prefs: SharedPreferences, state: State) {
        prefs.edit().putString(KEY, state.name).apply()
    }

    fun read(prefs: SharedPreferences): State {
        val stored = prefs.getString(KEY, null) ?: return State.IDLE
        return runCatching { State.valueOf(stored) }.getOrDefault(State.IDLE)
    }

    /**
     * Строка для колофона; null — когда говорить не о чем.
     *
     * [State.DELIVERED] тоже молчит: «всё хорошо» — не новость, а шум. Книга
     * подаёт голос только тогда, когда общая часть НЕ работает.
     */
    fun line(state: State): String? = when (state) {
        State.IDLE, State.DELIVERED -> null
        State.NO_ACCOUNT -> "Общая книга недоступна: вход не выполнен."
        State.DENIED -> "Общая книга недоступна: сервер не принял вход — войдите заново."
        State.UNREACHABLE -> "Общая книга недоступна: сервер не ответил, отправка подождёт."
        State.REJECTED -> "Общая книга недоступна: сервер не принял запись."
    }
}
