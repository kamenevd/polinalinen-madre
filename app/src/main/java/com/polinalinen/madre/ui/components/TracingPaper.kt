package com.polinalinen.madre.ui.components

/**
 * DESIGN-V4.md Cycle 9, фича «Калька» (TracingPaper). В настоящих семейных
 * книгах особые страницы — юбилейные — прокладывают калькой с припиской от
 * руки.
 *
 * Cycle 12: самого листа больше нет. Полупрозрачная калька ложилась поверх
 * всей страницы «Готово», забирала себе тапы и уходила только горизонтальным
 * свайпом — то есть между «испекла» и «на главную» вставал слой, который надо
 * было сначала догадаться смахнуть. Осталось то, ради чего калька и заводилась:
 * приписка Мадре на юбилейной выпечке. Теперь она просто написана на странице
 * (BakingCompleteScreen).
 */
object TracingPaper {
    /**
     * Юбилейные выпечки: первая, десятая, двадцать пятая, дальше — каждые
     * пятьдесят. Между ними приписки в книге не появляется.
     */
    fun isMilestone(totalBakes: Int): Boolean =
        totalBakes == 1 || totalBakes == 10 || totalBakes == 25 ||
            (totalBakes > 0 && totalBakes % 50 == 0)

    /** Приписка Мадре карандашом; null — выпечка не юбилейная. */
    fun noteFor(totalBakes: Int): String? = when {
        totalBakes == 1 -> "первая страница нашей книги. пусть их будет много"
        totalBakes == 10 -> "десятая выпечка. у нас с вами уже свои привычки"
        totalBakes == 25 -> "двадцать пятая. я узнаю ваши руки без подсказок"
        isMilestone(totalBakes) -> "выпечка № $totalBakes — юбилейная страница"
        else -> null
    }
}
